-- เดิมเจ้าหน้าที่ลบแถวในตาราง verify ได้ ทั้งที่ลบระเบียนสมาชิกไม่ได้
-- ช่องนี้ทำให้เจ้าหน้าที่ทำลายคิวอาร์โค้ดบนบัตรของสมาชิกได้โดยที่ตัวระเบียน
-- ยังอยู่ ซึ่งขัดกับหลักที่ชมรมวางไว้ว่าเจ้าหน้าที่ทำลายข้อมูลไม่ได้
-- การลบแถว verify เกิดขึ้นเฉพาะตอนลบสมาชิกเท่านั้น จึงให้สิทธิ์ตรงกัน
drop policy verify_delete on public.verify;
create policy verify_delete on public.verify for delete using (app.is_owner());
